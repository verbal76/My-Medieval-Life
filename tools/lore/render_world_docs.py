"""Render the reference deliverables in docs/world/ from the registries.

Reads research/registries/*.json (built by build_registries.py) and writes:

    docs/world/A_ENCYCLOPEDIA.md     people, groups, items, customs, beings, texts, with their facts
    docs/world/B_GAZETTEER.md        places, features, buildings and polities, with every map constraint
    docs/world/C_RELATIONSHIPS.md    the relationship graph as readable lists
    docs/world/E_ECONOMY.md          economy, trade, prices, crafts and production
    docs/world/F_TIMELINE.md         events by layer, in reading order
    research/registries/graph.json   nodes and edges for tools

These files are generated: edit the chapter notes or merges.json and rebuild, never the output.
The hand-written deliverables (D, G, H, I, J) live beside them.

Usage:
    python3 tools/lore/build_registries.py && python3 tools/lore/render_world_docs.py
"""
import json
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
REG = REPO / "research" / "registries"
DOCS = REPO / "docs" / "world"
BOOKS = {"BONE": 1, "BTWO": 2, "BTHREE": 3, "BFOUR": 4}
BOOK_NAME = {"BONE": "I", "BTWO": "II", "BTHREE": "III", "BFOUR": "IV"}
PLACE_TYPES = ["polity", "place", "feature", "building", "implicit place"]
ENC_TYPES = ["person", "group", "supernatural", "creature", "item", "text", "custom", "office",
             "occupation", "commodity", "currency", "implicit"]
ECON = {"economy", "price", "trade", "occupation", "craft", "agriculture", "transport", "food",
        "clothing", "household"}
HEADER = ("Generated by `tools/lore/render_world_docs.py` from `research/registries/`. Do not edit "
          "by hand. Labels: **CANON** = stated in the novel; **INF** = CANON-INFERRED (a "
          "reasonable reading, not stated). Every claim cites a paragraph id "
          "(`BONE-C3-P012` = Book One, chapter 3, paragraph 12) with a verbatim quote in the "
          "registry JSON.")


def load(name):
    return json.loads((REG / f"{name}.json").read_text())["records"]


def ckey(cid):
    b, n = cid.split("-")[:2]
    return BOOKS[b], int(n[1:])


def cite(refs, n=2):
    return ", ".join(f"`{r['p']}`" for r in refs[:n])


def short_ch(cid):
    b, n = cid.split("-")[:2]
    return f"{BOOK_NAME[b]}.{n[1:]}"


def cls(r):
    c = "CANON" if r.get("classification") == "CANON" else "INF"
    return f"{c}/{r.get('confidence', '')}".rstrip("/")


def ctx(r):
    c = r.get("context", "narration")
    return "" if c in ("narration", "narrator", "") else f", {c}"


def spatial_line(s, me):
    rel = s["rel"].replace("_", " ")
    if s["a"] == me:
        head = f"{rel} **{s['b']}**"
    elif s["rel"] in ("distance_from", "other", "near", "between", "on_route", "route_next"):
        head = f"**{s['a']}**: {rel} this"
    else:
        head = f"**{s['a']}** is {rel} this"
    bits = [x for x in (s.get("direction"), s.get("distance_text"), s.get("travel_time_text"),
                        s.get("travel_mode"), s.get("terrain_text")) if x]
    detail = f" ({'; '.join(bits)})" if bits else ""
    note = f" {s['note'].rstrip('.')}." if s.get("note") not in ("", "-", None) else ""
    return f"- {head}{detail}.{note} *{s['certainty']}, {cls(s)}{ctx(s)}*: {cite(s['refs'])}"


def kind(e):
    """Implicit entities named as places file with the gazetteer, the rest with the encyclopedia."""
    if e["implicit"]:
        return "implicit place" if e["subtypes"][0] == "place" else "implicit"
    return e["types"][0]


def entity_block(e, facts, rels, spatial, events, with_spatial):
    t = "/".join(e["types"])
    sub = ", ".join(e["subtypes"][:3])
    L = [f"### {e['name']}", "",
         f"`{e['id']}` · {t}{' · ' + sub if sub else ''} · chapters "
         f"{', '.join(short_ch(c) for c in e['chapters'][:12])}{' …' if len(e['chapters']) > 12 else ''}"]
    if e.get("geo_certainty"):
        L[-1] += f" · geography: **{e['geo_certainty']}**"
    if e["aliases"]:
        L += ["", "Also: " + "; ".join(e["aliases"])]
    if e["implicit"]:
        L += ["", "*Named only in relations, journeys or events; no entity record of its own.*"]
    seen = set()
    for s in e["summaries"]:
        if s["text"] not in seen:
            seen.add(s["text"])
            L += ["", f"- ({short_ch(s['chapter'])}) {s['text']}"]
    if e["possible_same_as"]:
        L += ["", "Possibly the same as: " + "; ".join(f"{x['name']} (`{x['id']}`): {x['basis']}"
                                                     for x in e["possible_same_as"])]
    if with_spatial and spatial:
        L += ["", "**Map constraints**", ""] + [spatial_line(s, e["name"]) for s in spatial]
    if facts:
        L += ["", "**Facts**", ""]
        L += [f"- [{f['category']}] {f['statement']} *{cls(f)}{ctx(f)}*: {cite(f['refs'], 1)}" for f in facts]
    if rels:
        L += ["", "**Relations**", ""]
        for r in rels:
            when = f", {r['when']}" if r.get("when") else ""
            L.append(f"- {r['a']} **{r['rel'].replace('_', ' ')}** {r['b']}"
                     f"{': ' + r['detail'] if r.get('detail') else ''} *{cls(r)}{when}*: {cite(r['refs'], 1)}")
    if events:
        L += ["", "**Appears in events**: " + "; ".join(f"{v['label']} ({short_ch(v['chapter'])})" for v in events[:15])]
    return L + [""]


def main():
    ents = load("entities")
    facts, rels, spatial = load("facts"), load("relations"), load("spatial")
    events, travel = load("events"), load("travel")
    by = {k: defaultdict(list) for k in ("facts", "rels", "spatial", "events")}
    for f in facts:
        by["facts"][f["subject"]].append(f)
    for r in rels:
        by["rels"][r["a"]].append(r)
        if r["b"] != r["a"]:
            by["rels"][r["b"]].append(r)
    for s in spatial:
        by["spatial"][s["a"]].append(s)
        if s["b"] != s["a"]:
            by["spatial"][s["b"]].append(s)
    for v in events:
        for n in set(v["participants"] + v["places"]):
            by["events"][n].append(v)
    for d in by.values():
        for v in d.values():
            v.sort(key=lambda r: (ckey(r["chapter"]), r["id"]))
    DOCS.mkdir(parents=True, exist_ok=True)

    def section(types, title, intro, with_spatial):
        L = [f"# {title}", "", HEADER, "", intro, ""]
        for t in types:
            group = sorted((e for e in ents if kind(e) == t), key=lambda e: e["name"].removeprefix("(unnamed) ").lower())
            if not group:
                continue
            L += [f"## {t.capitalize()} ({len(group)})", ""]
            for e in group:
                n = e["name"]
                L += entity_block(e, by["facts"][n], by["rels"][n], by["spatial"][n], by["events"][n], with_spatial)
        return "\n".join(L)

    (DOCS / "A_ENCYCLOPEDIA.md").write_text(section(
        ENC_TYPES, "A. Encyclopedia of The Well at the World's End",
        "People, groups, beings, items, texts, customs and offices, with every fact and relation "
        "extracted for them. Places are in the gazetteer (B). Implicit entries are names used in "
        "the records without a description of their own.", False))
    (DOCS / "B_GAZETTEER.md").write_text(section(
        PLACE_TYPES, "B. Gazetteer",
        "Every place, feature, building and polity, with every map constraint the text gives. "
        "Geography certainty: **fixed** = stated plainly; **constrained** = partly determined "
        "(a direction without a distance, a sequence); **flexible** = exists but placement is open; "
        "**unplaced** = no spatial statement at all. **Original** (game-invented) places are not "
        "listed here; see H and G.", True))

    # C. relationships
    people = {e["name"] for e in ents if e["types"][0] in ("person", "group", "polity", "supernatural")}
    L = ["# C. Relationship graph", "", HEADER, "",
         "Non-spatial relations between people, groups and polities. `when` gives the chapter or "
         "period a relation holds; many change during the story (e.g. the Lordship of Utterbol). "
         "Machine-readable nodes and edges: `research/registries/graph.json`.", ""]
    groups = defaultdict(list)
    for r in rels:
        groups[r["rel"]].append(r)
    for rel in sorted(groups):
        L += [f"## {rel.replace('_', ' ')} ({len(groups[rel])})", ""]
        for r in sorted(groups[rel], key=lambda r: (r["a"].lower(), ckey(r["chapter"]))):
            when = f", {r['when']}" if r.get("when") else ""
            L.append(f"- {r['a']} → {r['b']}{': ' + r['detail'] if r.get('detail') else ''} "
                     f"*{cls(r)}{when}*: {cite(r['refs'], 1)}")
        L.append("")
    (DOCS / "C_RELATIONSHIPS.md").write_text("\n".join(L))
    nodes = [{"id": e["id"], "name": e["name"], "type": e["types"][0]} for e in ents
             if e["name"] in people or any(e["name"] in (r["a"], r["b"]) for r in rels)]
    edges = [{"id": r["id"], "source": r["a_id"], "target": r["b_id"], "rel": r["rel"],
              "when": r.get("when", ""), "classification": r["classification"],
              "confidence": r["confidence"]} for r in rels]
    (REG / "graph.json").write_text(json.dumps({"format": "morris-graph/1", "nodes": nodes,
                                                "edges": edges}, indent=1, ensure_ascii=False) + "\n")

    # E. economy
    L = ["# E. Economy catalogue", "", HEADER, "",
         "Everything the novel says about money, prices, trade, crafts, food, clothing, farming, "
         "transport and households, grouped by category and subject. Commodities and currencies are "
         "listed first.", ""]
    for t in ("commodity", "currency", "occupation"):
        g = sorted((e for e in ents if e["types"][0] == t), key=lambda e: e["name"].lower())
        if g:
            L += [f"## {t.capitalize()} entities", ""]
            L += [f"- **{e['name']}** (`{e['id']}`): {e['summaries'][0]['text']} {cite(e['refs'], 1)}" for e in g]
            L.append("")
    cats = defaultdict(list)
    for f in facts:
        if f["category"] in ECON:
            cats[f["category"]].append(f)
    for c in sorted(cats):
        L += [f"## {c.capitalize()} ({len(cats[c])})", ""]
        for f in sorted(cats[c], key=lambda f: (f["subject"].lower(), ckey(f["chapter"]))):
            L.append(f"- **{f['subject']}**: {f['statement']} *{cls(f)}{ctx(f)}*: {cite(f['refs'], 1)}")
        L.append("")
    (DOCS / "E_ECONOMY.md").write_text("\n".join(L))

    # F. timeline
    L = ["# F. Timeline", "", HEADER, "",
         "Events in reading order, by layer. **main** = the story as it happens; **backstory** = "
         "earlier events told in the story; **legend** = tales of the deep past; **prophecy** = "
         "foretellings; **rumour** = unconfirmed reports; **epilogue** = after the homecoming. "
         "The novel gives almost no calendar dates: season and time-of-day words are quoted as given. "
         "Journeys are in `research/registries/travel.json` (" + str(len(travel)) + " records).", ""]
    for layer in ("main", "backstory", "legend", "prophecy", "rumour", "epilogue"):
        ev = sorted((v for v in events if v["layer"] == layer), key=lambda v: (ckey(v["chapter"]), v["id"]))
        if not ev:
            continue
        L += [f"## {layer.capitalize()} ({len(ev)})", "", "| Ch. | Event | When | Where | Summary | Ref |", "|---|---|---|---|---|---|"]
        for v in ev:
            row = [short_ch(v["chapter"]), v["label"], v.get("time_text", ""), ", ".join(v["places"]),
                   v["summary"], cite(v["refs"], 1)]
            L.append("| " + " | ".join(x.replace("|", "/") for x in row) + " |")
        L.append("")
    (DOCS / "F_TIMELINE.md").write_text("\n".join(L))
    print("wrote A, B, C, E, F and graph.json")


if __name__ == "__main__":
    main()
