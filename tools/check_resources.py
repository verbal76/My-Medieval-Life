def _instances(ctx, n):
    """(count, total text) of a node's instances in the map and balance."""
    m, v = n["match"], ctx["village"]
    if m["kind"] == "deposit":
        ds = [d for d in v["deposits"] if d["ore"] == m["ore"]]
        return len(ds), "%d %s in %d seams" % (sum(d["amount"] for d in ds), m["ore"], len(ds))
    if m["kind"] == "boulder":
        w = v["w"]
        t = ctx["res"]["deposit_tiles"]
        seams = {(d["x"], d["y"]) for d in v["deposits"]}
        look = set(t["flecked"]) | {t["boulder"]}
        cells = set()
        for lay in v["layers"]:
            if lay["name"].startswith("below"):
                for i, tv in enumerate(lay["data"]):
                    c = (i % w, i // w)
                    if tv in look and c not in seams and v["solid"][c[1]][c[0]] == "1":
                        cells.add(c)
        return len(cells), "%d in the village (%d stone each), and the overworld's solid rocks" % (len(cells), n["uses"])
    if m["kind"] == "tree":
        return len(v["trees"]), "%d trees, %d logs while all are grown" % (len(v["trees"]), len(v["trees"]) * products(ctx, n)["log"])
    if m["kind"] == "field":
        y = ctx["balance"]["field_yield"]
        return len(v["fields"]), "%d fields of %d wheat: %d a ripening" % (len(v["fields"]), y, y * len(v["fields"]))
    if m["kind"] == "player_field":
        return 0, "as many cells as the player clears and tills on ground they hold (PL2-015)"
    if m["kind"] == "player_pen":
        return 0, "as many pens as the player fences on ground they hold, each with at most pen_cap animals (PL2-015)"
    if m["kind"] == "fruit_tree":
        f = ctx["balance"]["fruit_trees"]
        return 0, "the village trees within %d tiles of a house door, one in %d (new worlds), and any planted from saplings; %d %s a picking" % (
            f["orchard_house_range"], f["orchard_share"], f[m["species"]]["yield"], f[m["species"]]["item"])
    if m["kind"] == "clue":
        pc = json.loads((ctx["root"] / "game" / "data" / "prospecting.json").read_text())
        return 0, "generated from the world seed (MIN-C): a clue in about %d%% of the village's %d-cell blocks, %d samples each; %d%% lie over a mineral body" % (
            pc["clue_percent"], pc["block"], pc["samples_per_clue"], pc["true_percent"])
    if m["kind"] == "tunnel":
        wc = json.loads((ctx["root"] / "game" / "data" / "mine_works.json").read_text())
        return 0, "cut in play below ground (MIN-F): each rock cell under the hill gives %s" % (
            ", ".join("%d %s" % (l["amount"], l["item"]) for l in wc["cell"]))
    if m["kind"] == "pit":
        pc = json.loads((ctx["root"] / "game" / "data" / "open_pit.json").read_text())
        return 0, "staked in play (MIN-E): each %d x %d cells over the layers %s" % (
            pc["size"], pc["size"], ", ".join("%d %s" % (l["amount"], l["item"]) for l in pc["layers"]))
    if m["kind"] == "plant":
        n_pl = sum(1 for pl in v.get("plants", []) if pl["kind"] == m["plant"])
        return n_pl, "%d plants on the map, each ripe again plant_regrow_seasons after it is picked" % n_pl
    sp = ctx["balance"]["animals"][m["species"]]
    start = sum(sp["start"])
    if sp["kind"] == "wild":
        w = len(v.get("woods", []))
        return start * w, "%d at the start (%d male, %d female in each of %d woods), at most %d a wood; hunters keep %d adults" % (
            start * w, sp["start"][0], sp["start"][1], w, sp["woods_cap"], sp["keep"])
    pens = [p for p in v.get("pens", []) if p["kind"] == m["species"]]
    return start * len(pens), "%d at the start (%d male, %d female) in %d pen, at most %d; the keeper keeps %d" % (
        start * len(pens), sp["start"][0], sp["start"][1], len(pens), sp["pen_cap"], sp["keep"])


def _tool_from(ctx, n):
    tool = n.get("tool", "")
    if not tool:
        return "none"
    if tool == "weapon":
        its = sorted(i for i, it in ctx["items"].items() if it["type"] == "weapon")
    else:
        its = sorted(i for i, it in ctx["items"].items() if it.get("tool") == tool)
    parts = []
    for i in its:
        src = ["%s (%s)" % (k.replace("_", " "), x) for k, x, *_ in sources_of(ctx, i) if k in ("recipe", "start_kit")]
        sellers = sorted(r for r, caps in ctx["buys"].items() if i in caps)
        parts.append("`%s`: %s%s" % (i, ", ".join(src) if src else "no recipe or kit",
                                       ("; resold by the " + ", ".join(sellers)) if sellers else ""))
    return "; ".join(parts)


