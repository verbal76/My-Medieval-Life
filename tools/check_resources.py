# ---------------------------------------------------------------- loading --------------------
def _unique_pairs(pairs):
    seen = {}
    for k, v in pairs:
        if k in seen:
            raise ValueError("duplicate key %r" % k)
        seen[k] = v
    return seen


def load(root=ROOT):
    """Everything the checks and documents read, as one dict (`ctx`)."""
    data = root / "game" / "data"
    core = root / "game" / "scripts" / "core"
    ctx = {"root": root, "dup": []}
    try:
        ctx["res"] = json.loads((data / "resources.json").read_text(), object_pairs_hook=_unique_pairs)
    except ValueError as e:
        ctx["dup"].append(str(e))
        ctx["res"] = json.loads((data / "resources.json").read_text())
    ctx["items"] = json.loads((data / "items.json").read_text())["items"]
    ctx["recipes"] = json.loads((data / "recipes.json").read_text())["recipes"]
    ctx["balance"] = json.loads((data / "balance.json").read_text())
    ctx["quests"] = json.loads((data / "quests.json").read_text())["quests"]
    ctx["village"] = json.loads((data / "village.json").read_text())
    brain = (core / "npc_brain.gd").read_text()
    ctx["buys"] = gd_const(brain, "BUYS")
    ctx["not_exported"] = gd_const(brain, "NOT_EXPORTED")
    ctx["smith_caps"] = ast.literal_eval(re.search(r"caps = (\{[^}]*\})", func_body(brain, "caravan")).group(1))
    ctx["manor_materials"] = gd_const((core / "manor_work.gd").read_text(), "MATERIALS")
    ctx["fell_logs"] = int(re.search(r"return (\d+) \+ bonus", func_body((core / "world.gd").read_text(), "fell")).group(1))
    return ctx


def gd_const(text, name):
    """A GDScript `const NAME := {...}` or `[...]` literal as Python data (comments dropped)."""
    m = re.search(r"^const %s := " % re.escape(name), text, re.M)
    i = m.end()
    depth, j = 0, i
    while True:
        c = text[j]
        if c in "{[":
            depth += 1
        elif c in "}]":
            depth -= 1
            if depth == 0:
                break
        j += 1
    lit = re.sub(r"#[^\n]*", "", text[i:j + 1])
    return ast.literal_eval(lit)


def func_body(text, name):
    """The lines of a GDScript function, from its `func` line to the next unindented line."""
    lines = text.splitlines()
    for n, line in enumerate(lines):
        if re.match(r"^(static )?func %s\(" % re.escape(name), line):
            body = [line]
            for more in lines[n + 1:]:
                if more.strip() and not more[0].isspace():
                    break
                body.append(more)
            return "\n".join(body)
    return ""


def added_items(body):
    """Items a function body adds to an inventory: `.add("x"` and `_give(inv, {...})`."""
    out = set(re.findall(r'\.add\("(\w+)"', body))
    for lit in re.findall(r"_give\(\w+, (\{[^}]*\})\)", body):
        out |= set(ast.literal_eval(lit))
    return out


def bal(ctx, key):
    """A balance.json value by dotted key, or None."""
    at = ctx["balance"]
    for part in str(key).split("."):
        if not isinstance(at, dict) or part not in at:
            return None
        at = at[part]
    return at


def num(ctx, v):
    return bal(ctx, v) if isinstance(v, str) else v


# ---------------------------------------------------------------- derived facts --------------
def products(ctx, node):
    out = {}
    for item, v in sorted(node.get("yields", {}).items()):
        n = num(ctx, v)
        if isinstance(n, (int, float)) and n > 0:
            out[item] = n
    return out


def imports(ctx):
    """item -> [import note]."""
    out = {}
    for n in ctx["res"].get("imports", []):
        items = list(bal(ctx, n["items_key"]) or {}) if "items_key" in n else n.get("items", [])
        for i in items:
            out.setdefault(i, []).append(n)
    return out


def exported(ctx, item):
    if item in ctx["not_exported"]:
        return False
    return any(r.startswith("merchant_") and item in caps for r, caps in ctx["buys"].items()) or \
        item in ctx["res"].get("exports", {}).get("smith_caps", {})


def building_costs(ctx):
    out = {"house": ctx["balance"]["house_cost"]}
    out.update(ctx["balance"].get("workshop_cost", {}))
    return out


def sources_of(ctx, item):
    """[(kind, id, qty, text)], as ResourceNodes.sources_of."""
    out = []
    for nid, node in sorted(ctx["res"]["nodes"].items()):
        p = products(ctx, node)
        if item in p:
            out.append(("node", nid, p[item], node["name"]))
    for r, rec in sorted(ctx["recipes"].items()):
        if item in rec["out"]:
            out.append(("recipe", r, rec["out"][item], "%s at the %s" % (r.replace("_", " "), rec["station"])))
    kit = ctx["balance"].get("player_start_items", {})
    if item in kit:
        out.append(("start_kit", "player_start_items", kit[item], "the player's start kit"))
    for i, n in enumerate(ctx["res"].get("code_sources", [])):
        if item in n["items"]:
            out.append(("start_stock", "start_%d" % i, 0, n["text"]))
    for n in imports(ctx).get(item, []):
        out.append(("import", "caravan", 0, n["text"]))
    return sorted(out)


def uses_of(ctx, item):
    """[(kind, id, qty, text)], as ResourceNodes.uses_of."""
    out = []
    for r, rec in sorted(ctx["recipes"].items()):
        if item in rec["in"]:
            out.append(("recipe", r, rec["in"][item], "%s at the %s" % (r.replace("_", " "), rec["station"])))
    for role, caps in sorted(ctx["buys"].items()):
        if item in caps:
            out.append(("buyer", role, caps[item], "bought by the %s" % role.replace("_", " ")))
    if exported(ctx, item):
        out.append(("export", "caravan", 0, "bought by the passing caravan"))
    for k, cost in sorted(building_costs(ctx).items()):
        if item in cost:
            out.append(("building", k, cost[item], "building a %s" % k))
    for q in ctx["quests"]:
        if item in q.get("need", {}):
            out.append(("quest", q["id"], q["need"][item], q["title"]))
    it = ctx["items"].get(item, {})
    if it.get("food", 0) > 0:
        out.append(("food", item, it["food"], "eaten (%d food)" % it["food"]))
    if it.get("type") in EQUIP:
        out.append(("equip", it["type"], 1, "worn or used as a %s" % it["type"]))
    if "tool" in it:
        for nid, node in sorted(ctx["res"]["nodes"].items()):
            if node.get("tool") == it["tool"] and node.get("tool_required"):
                out.append(("tool", nid, 1, "the tool for %s" % node["verb"].lower()))
    for n in ctx["res"].get("materials", {}).get(item, []):
        out.append((n["use"], item, 0, n["text"]))
    return sorted(out)


CONSUMING = {"recipe", "building", "quest", "food", "equip", "tool", "fuel", "feed", "manor_job", "home_cooking", "granary", "plant", "assay", "backfill"}


def reachable(ctx, node_ok):
    """Items that can be had again and again: products of the nodes `node_ok` accepts, imports, and
    whatever recipes make from those."""
    have = set()
    for node in ctx["res"]["nodes"].values():
        if node_ok(node):
            have |= set(products(ctx, node))
    if node_ok is not RENEWABLE:
        have |= set(imports(ctx))
    grew = True
    while grew:
        grew = False
        for rec in ctx["recipes"].values():
            if all(i in have for i in rec["in"]) and not all(o in have for o in rec["out"]):
                have |= set(rec["out"])
                grew = True
    return have


def RENEWABLE(node):
    return node["depletion"] != "finite"


def chain_lines(ctx, item, depth=6, path=(), indent=0):
    """Markdown bullet lines: what `item` becomes through recipes."""
    out = []
    if depth <= 0 or item in path:
        return out
    for r, rec in sorted(ctx["recipes"].items()):
        if item not in rec["in"]:
            continue
        others = {k: v for k, v in rec["in"].items() if k != item}
        made = ", ".join("%d %s" % (v, k) for k, v in sorted(rec["out"].items()))
        extra = (" + " + ", ".join("%d %s" % (v, k) for k, v in sorted(others.items()))) if others else ""
        out.append("%s- %d %s%s → **%s** (%s, %s)" % ("  " * indent, rec["in"][item], item, extra, made, r, rec["station"]))
        for o in sorted(rec["out"]):
            out += chain_lines(ctx, o, depth - 1, path + (item,), indent + 1)
    return out


def chain_paths(ctx, item, path=()):
    """Every recipe path from `item` to an item no recipe consumes: lists of items."""
    path = path + (item,)
    nxt = sorted({o for rec in ctx["recipes"].values() if item in rec["in"] for o in rec["out"]} - set(path))
    if not nxt:
        return [path]
    out = []
    for o in nxt:
        out += chain_paths(ctx, o, path)
    return out


def raw_needs(ctx, item, qty=1.0, path=()):
    """Raw materials (items no recipe makes, or made in a loop) for `qty` of `item`: item -> amount."""
    makers = [rec for r, rec in sorted(ctx["recipes"].items()) if item in rec["out"]]
    if not makers or item in path:
        return {item: qty}
    rec = makers[0]
    runs = qty / rec["out"][item]
    out = {}
    for i, n in sorted(rec["in"].items()):
        for k, v in raw_needs(ctx, i, runs * n, path + (item,)).items():
            out[k] = out.get(k, 0.0) + v
    return out


def fmt(n):
    return ("%d" % n) if float(n).is_integer() else ("%.2f" % n).rstrip("0")


def summary(ctx):
    """The counts and lists the documents and the owner's report give."""
    res, items, recipes = ctx["res"], ctx["items"], ctx["recipes"]
    nodes = res["nodes"]
    exc = {e["item"]: e for e in res.get("exceptions", [])}
    renew = reachable(ctx, RENEWABLE)
    legit = reachable(ctx, lambda n: True)
    s = {}
    s["implemented_nodes"] = sorted(n for n in nodes if nodes[n]["status"] == "implemented")
    s["player_nodes"] = sorted(n for n in nodes if nodes[n]["player_harvest"])
    s["materials"] = sorted({i for n in nodes.values() for i in products(ctx, n)})
    s["player_materials"] = sorted({i for n in nodes.values() if n["player_harvest"] for i in products(ctx, n)})
    roots = s["materials"]
    s["chains"] = sorted({p for i in roots for p in chain_paths(ctx, i) if len(p) > 1})
    s["no_source"] = sorted(i for i in items if not sources_of(ctx, i))
    s["kit_only"] = sorted(i for i in items if sources_of(ctx, i) and all(k == "start_kit" for k, *_ in sources_of(ctx, i)))
    s["not_legit"] = sorted(i for i in items if i not in legit)
    s["materials_no_use"] = sorted(i for i, it in items.items() if it["type"] == "resource"
                                   and not any(k in CONSUMING for k, *_ in uses_of(ctx, i)))
    s["no_use"] = sorted(i for i in items if not uses_of(ctx, i))
    s["dead_ends"] = sorted(i for i in items if not any(i in rec["in"] for rec in recipes.values()))
    s["missing_recipes"] = sorted(r for r, rec in recipes.items() if not all(i in legit for i in rec["in"]))
    s["finite"] = sorted(n for n in nodes if nodes[n]["depletion"] == "finite")
    s["finite_no_replacement"] = sorted(n for n in s["finite"] if not all(i in imports(ctx) for i in products(ctx, nodes[n])))
    s["import_dependent"] = sorted(i for i in legit if i not in renew and sources_of(ctx, i))
    s["at_risk"] = sorted(n for n in nodes if nodes[n]["risk"].startswith("Overharvested"))
    s["not_gather"] = sorted(n for n in nodes if not nodes[n]["gather"])
    s["exceptions"] = exc
    return s


# ---------------------------------------------------------------- checks ---------------------
def _ref_ok(root, ref):
    path, _, name = ref.partition("::")
    p = root / path
    if not p.is_file():
        return "file not found: %s" % path
    if name and not _defines(p, name):
        return "%s has no func %s" % (path, name)
    return ""


def station_types(ctx):
    """Every station type a recipe can name: the map's stations, the workshops' (village.json stamps)
    and a home's furniture (PL2-013: Furniture.STATION_OF maps a spot kind to its station type)."""
    stations = {s["type"] for s in ctx["village"]["stations"]}
    for st in ctx["village"].get("stamps", {}).values():
        stations |= {s["type"] for s in st.get("stations", [])}
    furn = (ROOT / "game/scripts/core/furniture.gd").read_text(encoding="utf-8")
    m = re.search(r"const STATION_OF := \{([^}]*)\}", furn)
    stations |= set(re.findall(r':\s*"([a-z_]+)"', m.group(1))) if m else set()
    return stations


def problems(ctx):
    out = list("resources.json: " + d for d in ctx["dup"])
    res, items, recipes, bal_ = ctx["res"], ctx["items"], ctx["recipes"], ctx["balance"]
    root = ctx["root"]
    enums = res.get("enums", {})
    nodes = res.get("nodes", {})
    if res.get("format") != FORMAT:
        out.append("format is %r, not %r" % (res.get("format"), FORMAT))
    tool_types = {it["tool"] for it in items.values() if "tool" in it}
    stations = station_types(ctx)

    def item_ok(where, i):
        if i not in items:
            out.append("%s: unknown item %r" % (where, i))

    def ref_ok(where, ref):
        why = _ref_ok(root, ref)
        if why:
            out.append("%s: %s" % (where, why))

    # nodes
    for nid, n in sorted(nodes.items()):
        for f in NODE_FIELDS:
            if f not in n or n[f] is None or (isinstance(n[f], str) and f not in ("tool", "skill") and not n[f].strip()):
                out.append("%s: missing %s" % (nid, f))
        for f, enum in (("category", "category"), ("origin", "origin"), ("depletion", "depletion"), ("status", "status"), ("action", "action")):
            if n.get(f) not in enums.get(enum, []):
                out.append("%s: %s %r is not one of %s" % (nid, f, n.get(f), enums.get(enum)))
        for f in ("npc_harvest", "player_harvest", "gather", "tool_required"):
            if not isinstance(n.get(f), bool):
                out.append("%s: %s must be true or false" % (nid, f))
        if n.get("player_harvest") is True and n.get("gather") is not True:
            out.append("%s: a player-harvestable node needs gather true" % nid)
        if n.get("player_harvest") is False and n.get("gather") is True:
            out.append("%s: gather is true but the player cannot harvest it" % nid)
        if not isinstance(n.get("range"), (int, float)) or n.get("range", 0) <= 0:
            out.append("%s: range must be a positive number of tiles" % nid)
        tool = n.get("tool", "")
        if tool and tool != "weapon" and tool not in tool_types:
            out.append("%s: tool %r is no item's tool type (%s)" % (nid, tool, sorted(tool_types)))
        if tool == "weapon" and not any(it["type"] == "weapon" for it in items.values()):
            out.append("%s: no weapon item exists" % nid)
        if n.get("tool_required") and not tool:
            out.append("%s: a tool is required but none named" % nid)
        if n.get("skill") and n["skill"] not in json.loads((root / "game/data/skills.json").read_text())["skills"]:
            out.append("%s: unknown skill %r" % (nid, n["skill"]))
        if "minutes_key" in n:
            if not isinstance(bal_.get(n["minutes_key"]), (int, float)):
                out.append("%s: minutes_key %r is not a balance.json number" % (nid, n["minutes_key"]))
        elif not isinstance(n.get("minutes"), (int, float)):
            out.append("%s: needs minutes_key or minutes" % nid)
        for i, v in sorted(n.get("yields", {}).items()):
            item_ok(nid + " yields", i)
            if not isinstance(num(ctx, v), (int, float)):
                out.append("%s: yield %s %r is not a number or balance key" % (nid, i, v))
        if not products(ctx, n):
            out.append("%s: yields nothing" % nid)
        item_ok(nid + " icon", n.get("icon", ""))
        if not n.get("owner") or not n.get("theft"):
            out.append("%s: owner and theft rules are required" % nid)
        for ref in n.get("sources", []):
            ref_ok(nid, ref)
        m = n.get("match", {})
        if m.get("kind") in ("deposit", "boulder"):
            item_ok(nid + " match", m.get("ore", ""))
            if m.get("kind") == "boulder" and (not isinstance(n.get("uses"), int) or n["uses"] < 1):
                out.append("%s: a boulder needs uses (a whole number of units it gives)" % nid)
        elif m.get("kind") == "animal":
            sp = bal_["animals"].get(m.get("species", ""))
            if not isinstance(sp, dict):
                out.append("%s: unknown species %r" % (nid, m.get("species")))
            elif (sp["kind"] == "wild") != (n.get("category") == "game") or (sp["kind"] == "livestock") == n.get("player_harvest"):
                out.append("%s: a %s species must be %s" % (nid, sp["kind"], "game the player may hunt" if sp["kind"] == "wild" else "livestock the player may not take"))
        elif m.get("kind") == "plant":
            if m.get("plant") not in {pl["kind"] for pl in ctx["village"].get("plants", [])}:
                out.append("%s: no plant of kind %r in village.json" % (nid, m.get("plant")))
        elif m.get("kind") == "fruit_tree":
            if not isinstance(bal_.get("fruit_trees", {}).get(m.get("species", "")), dict):
                out.append("%s: no fruit_trees entry %r in balance.json" % (nid, m.get("species")))
        elif m.get("kind") == "clue":
            if not (ctx["root"] / "game" / "data" / "prospecting.json").exists():
                out.append("%s: a clue node needs game/data/prospecting.json" % nid)
        elif m.get("kind") == "pit":
            pf = ctx["root"] / "game" / "data" / "open_pit.json"
            if not pf.exists():
                out.append("%s: a pit node needs game/data/open_pit.json" % nid)
            else:
                layer_items = {str(l["item"]) for l in json.loads(pf.read_text())["layers"]}
                if layer_items != set(products(ctx, n)):
                    out.append("%s: yields %s differ from open_pit.json's layers %s" % (nid, sorted(products(ctx, n)), sorted(layer_items)))
        elif m.get("kind") == "tunnel":
            wf = ctx["root"] / "game" / "data" / "mine_works.json"
            if not wf.exists():
                out.append("%s: a tunnel node needs game/data/mine_works.json" % nid)
            else:
                cell_items = {str(l["item"]) for l in json.loads(wf.read_text())["cell"]}
                if cell_items != set(products(ctx, n)):
                    out.append("%s: yields %s differ from mine_works.json's cell %s" % (nid, sorted(products(ctx, n)), sorted(cell_items)))
        elif m.get("kind") not in ("tree", "field", "player_field", "player_pen"):
            out.append("%s: unknown match kind %r" % (nid, m.get("kind")))
    # every harvestable kind in the map and balance has a node, and no kind has two
    keys = [(n["match"].get("kind"), n["match"].get("ore") or n["match"].get("species") or n["match"].get("plant") or "") for n in nodes.values() if "match" in n]
    for k in sorted({k for k in keys if keys.count(k) > 1}):
        out.append("two nodes match %s %s" % k)
    for ore in sorted({d["ore"] for d in ctx["village"]["deposits"]}):
        if ("deposit", ore) not in keys:
            out.append("deposit ore %r in village.json has no node" % ore)
    # one sprite, one product (B8-008): every ore has its own tile, only stone's is plain
    dt = res.get("deposit_tiles", {})
    for ore in sorted({k[1] for k in keys if k[0] == "deposit"} | set(dt.get("ore", {}))):
        if ore not in dt.get("ore", {}):
            out.append("deposit ore %r has no tile in deposit_tiles" % ore)
        item_ok("deposit_tiles", ore)
    tiles = dt.get("ore", {})
    flecked = set(dt.get("flecked", []))
    for ore, t in sorted(tiles.items()):
        if (ore == "stone") == (t in flecked):
            out.append("deposit_tiles: %s's tile %s must %sbe a flecked (ore) sprite" % (ore, t, "not " if ore == "stone" else ""))
    ore_tiles = [t for o, t in tiles.items() if o != "stone"]
    if len(set(ore_tiles)) != len(ore_tiles):
        out.append("deposit_tiles: two ores share a tile")
    if dt.get("boulder") != tiles.get("stone"):
        out.append("deposit_tiles: the boulder is the plain stone sprite")
    if dt.get("worked_out") in flecked or dt.get("worked_out") == dt.get("boulder"):
        out.append("deposit_tiles: worked_out must differ from the boulder and the flecked sprites")
    if ("boulder", "stone") not in keys:
        out.append("no boulder node (small grey boulders give stone)")
    for sp, spec in sorted(bal_["animals"].items()):
        if isinstance(spec, dict) and ("animal", sp) not in keys:
            out.append("%s species %r has no node" % (spec["kind"], sp))
    for pk in sorted({pl["kind"] for pl in ctx["village"].get("plants", [])}):
        if ("plant", pk) not in keys:
            out.append("plant kind %r in village.json has no node" % pk)
    if ctx["village"]["trees"] and ("tree", "") not in keys:
        out.append("the map has trees but no tree node")
    if ctx["village"]["fields"] and ("field", "") not in keys:
        out.append("the map has fields but no field node")
    # recipes
    for r, rec in sorted(recipes.items()):
        for i in list(rec["in"]) + list(rec["out"]):
            item_ok("recipe " + r, i)
        if rec["station"] not in stations:
            out.append("recipe %s: no %s station on the map or in a workshop" % (r, rec["station"]))
    # every other item named
    for role, caps in sorted(ctx["buys"].items()):
        for i in caps:
            item_ok("NPCBrain.BUYS." + role, i)
    for i in res.get("materials", {}):
        item_ok("materials", i)
        for n in res["materials"][i]:
            ref_ok("materials." + i, n["source"])
    for n in res.get("code_sources", []):
        for i in n["items"]:
            item_ok("code_sources", i)
        ref_ok("code_sources", n["source"])
    for n in res.get("imports", []):
        if "items_key" in n and not isinstance(bal(ctx, n["items_key"]), dict):
            out.append("imports: %r is not a balance.json table" % n["items_key"])
        for i in imports(ctx):
            item_ok("imports", i)
        ref_ok("imports", n["source"])
    ex = res.get("exports", {})
    for i in ex.get("smith_caps", {}):
        item_ok("exports.smith_caps", i)
    ref_ok("exports", ex.get("source", ""))
    for n in res.get("non_harvestable", []):
        if not n.get("reason"):
            out.append("non_harvestable %s: missing reason" % n.get("id"))
        ref_ok("non_harvestable " + str(n.get("id")), n.get("source", ""))
    # the code-defined notes match the code
    if ex.get("smith_caps") != ctx["smith_caps"]:
        out.append("exports.smith_caps %s differ from NPCBrain.caravan's %s" % (ex.get("smith_caps"), ctx["smith_caps"]))
    manor = sorted(i for i, ns in res.get("materials", {}).items() if any(n["use"] == "manor_job" for n in ns))
    if manor != sorted(ctx["manor_materials"]):
        out.append("materials with manor_job notes %s differ from ManorWork.MATERIALS %s" % (manor, sorted(ctx["manor_materials"])))
    by_src = {}
    for n in res.get("code_sources", []):
        by_src.setdefault(n["source"], set()).update(n["items"])
    for src, its in sorted(by_src.items()):
        path, _, name = src.partition("::")
        if (root / path).is_file():
            found = added_items(func_body((root / path).read_text(), name))
            if its != found:
                out.append("code_sources for %s list %s; the code adds %s" % (src, sorted(its), sorted(found)))
    tree = [n for n in nodes.values() if n.get("match", {}).get("kind") == "tree"]
    if tree and products(ctx, tree[0]).get("log") != ctx["fell_logs"]:
        out.append("the tree node yields %s logs; World.fell gives %d" % (products(ctx, tree[0]).get("log"), ctx["fell_logs"]))
    # findings: each recorded as an exception, and no exception stale
    s = summary(ctx)
    exc = s["exceptions"]
    for e in res.get("exceptions", []):
        item_ok("exceptions", e["item"])
        if e.get("finding") not in FINDINGS:
            out.append("exception %s: finding %r is not one of %s" % (e["item"], e.get("finding"), FINDINGS))
        if e.get("status") not in enums.get("status", []):
            out.append("exception %s: bad status %r" % (e["item"], e.get("status")))
        if not e.get("reason"):
            out.append("exception %s: missing reason" % e["item"])
    want = {}
    for i in s["no_source"]:
        want[i] = "no_source"
    for i in s["kit_only"]:
        want[i] = "start_kit_only"
    for i in s["not_legit"]:
        want.setdefault(i, "no_source")
    for i in s["materials_no_use"]:
        want[i] = "no_consumer"
    for i in s["import_dependent"]:
        if any(k == "node" for k, *_ in sources_of(ctx, i)):
            want.setdefault(i, "import")
    for i, f in sorted(want.items()):
        if i not in exc:
            out.append("finding not recorded: %s (%s): add an exception with a reason, or fix the game" % (i, f))
        elif exc[i]["finding"] != f:
            out.append("exception %s says %s; the finding is %s" % (i, exc[i]["finding"], f))
    for i in sorted(exc):
        if i not in want:
            out.append("stale exception: %s (%s) is no longer a finding" % (i, exc[i]["finding"]))
    ui = root / "game" / "scripts" / "ui" / "game_ui.gd"
    if ui.is_file():
        out += journal_problems(res, ui.read_text())
    return out


JOURNAL_PAGE = r"show_resources|_res_\w+"         # game_ui.gd: the journal's Resources & Gathering page
JOURNAL_CONSTS = r"GATHER_\w+|RES_\w+"


def journal_problems(res, text):
    """The journal's resources page must be built from the registry: its functions read
    ResourceNodes, and no string in them or in their constants names a node id, a node's name, a
    product or an icon (one list, resources.json, not a second one in the interface)."""
    names = sorted(set(re.findall(r"^func (%s)\(" % JOURNAL_PAGE, text, re.M)))
    bodies = [(f, func_body(text, f)) for f in names]
    if "show_resources" not in names or not any("ResourceNodes." in b for _, b in bodies):
        return ["game_ui.gd: the journal's resources page (show_resources) does not read ResourceNodes"]
    for m in re.finditer(r"^const (%s) := .*?(?=^\S)" % JOURNAL_CONSTS, text, re.M | re.S):
        bodies.append((m.group(1), m.group(0)))
    terms = set()
    for nid, n in res.get("nodes", {}).items():
        terms |= {nid, n.get("name", ""), n.get("icon", "")} | set(n.get("yields", {}))
    terms.discard("")
    out = []
    for name, body in bodies:
        for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', body):
            for t in sorted(terms):
                if re.search(r"(?<!\w)%s(?!\w)" % re.escape(t), lit, re.I):
                    out.append("game_ui.gd %s: the literal %r names %r from resources.json: read it through ResourceNodes"
                               % (name, lit, t))
    return out


