"""Validate game/data/resources.json and generate the resource manifests from it.

resources.json (format mml-resources/1) is the one authoritative definition of the village's
harvestable resource nodes and of the uses and sources the code defines; ResourceNodes
(game/scripts/core/resource_nodes.gd) reads it at run time. This tool checks it against the game's
data and code, then derives two documents from it, the data files and the code:

- docs/systems/RESOURCE_NODE_MANIFEST.md: every node, what it yields, how it depletes and regrows,
  who owns it, and the risks;
- docs/systems/RESOURCE_USAGE_REGISTRY.md: both directions (a node's products and what they become;
  an item or building's raw materials and nodes), and the findings: dead ends, orphaned items,
  recipes without legitimate sources, finite resources without replacement, import-dependent chains,
  overharvesting risks and the recorded exceptions.

Checks: every deposit ore, wild and livestock species, the trees and the fields have a node; ids are
unique; yields, icons and every item named anywhere are defined items; recipes consume and produce
defined items at existing stations; every item without a source and every material without a
consumer is a recorded exception (and no exception is stale); tool requirements name a real tool
type; every node has its fields, owner and theft rules, a valid depletion, and a gather flag;
minutes_key and balance keys exist; cited files and functions exist; the code-defined notes match the
code they cite (NPCBrain.BUYS items, the caravan's smith caps, ManorWork.MATERIALS, the start
stock, World.fell's logs); the journal's Resources & Gathering page (game_ui.gd show_resources
and its _res_* helpers) reads the registry through ResourceNodes and names no node, node name or
product in its own code; and the generated documents are current.

    python3 tools/check_resources.py           # check; exit 1 and list problems if any
    python3 tools/check_resources.py --write   # regenerate the two documents, then check
"""
