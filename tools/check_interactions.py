"""Validate docs/SYSTEM_INTERACTION_MANIFEST.md and regenerate its reverse dependency index.

Each entry is a `### INT-### · Title` heading followed by `- **Trigger:**`, `- **Source:**`,
`- **Affects:**`, `- **Expected:**` and `- **Tests:**` lines; indented bullets under a line continue it. Source and Tests cite files as
`path` or `path::function` (paths from the repository root); a cited function must be defined in
that file. Affects lists systems named in the manifest's Systems section.

Checks: ids are unique and increasing (ids are never reused or renumbered), every field is present,
every cited file and function exists, every affected system is defined, and the reverse index is
current.

    python3 tools/check_interactions.py           # check; exit 1 and list problems if any
    python3 tools/check_interactions.py --write   # rewrite the reverse index, then check
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "SYSTEM_INTERACTION_MANIFEST.md"
FIELDS = ["Trigger", "Source", "Affects", "Expected", "Tests"]
INDEX_START = "<!-- index:start (generated by tools/check_interactions.py --write) -->"
INDEX_END = "<!-- index:end -->"

ENTRY = re.compile(r"^### (INT-\d{3}) · (.+)$")
FIELD = re.compile(r"^- \*\*(\w+):\*\*\s*(.*)$")
MORE = re.compile(r"^\s+- (.*)$")          # an indented bullet continues the field above it
SYSTEM = re.compile(r"^- \*\*([^*]+)\*\*")
REF = re.compile(r"`([^`]+)`")


def parse(text):
    """Return (systems, entries). Each entry: {id, title, line, fields: {name: text}}."""
    systems, entries = [], []
    section = ""
    field = ""
    for n, line in enumerate(text.splitlines(), 1):
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        if section == "Systems":
            m = SYSTEM.match(line)
            if m:
                systems.append(m.group(1).strip())
            continue
        m = ENTRY.match(line)
        if m:
            entries.append({"id": m.group(1), "title": m.group(2).strip(), "line": n, "fields": {}})
            continue
        m = FIELD.match(line)
        if m and entries and section == "Interactions":
            field = m.group(1)
            entries[-1]["fields"][field] = m.group(2).strip()
            continue
        m = MORE.match(line)
        if m and entries and field and section == "Interactions":
            f = entries[-1]["fields"]
            f[field] = (f.get(field, "") + " " + m.group(1).strip()).strip()
    return systems, entries


def affects(entry):
    return [s.strip() for s in entry["fields"].get("Affects", "").split(",") if s.strip()]


def _defines(path, name):
    return re.search(r"^(static )?func %s\(" % re.escape(name), path.read_text(), re.M) is not None


def problems(text, root=ROOT):
    systems, entries = parse(text)
    out = []
    if not systems:
        out.append("no systems defined in the Systems section")
    if not entries:
        out.append("no interaction entries")
    last = 0
    seen = set()
    for e in entries:
        num = int(e["id"][4:])
        if e["id"] in seen:
            out.append("%s (line %d): duplicate id" % (e["id"], e["line"]))
        elif num <= last:
            out.append("%s (line %d): ids must increase" % (e["id"], e["line"]))
        seen.add(e["id"])
        last = max(last, num)
        for f in FIELDS:
            if not e["fields"].get(f):
                out.append("%s: missing %s" % (e["id"], f))
        for f in ("Source", "Tests"):
            refs = REF.findall(e["fields"].get(f, ""))
            if e["fields"].get(f) and not refs:
                out.append("%s: %s cites no file" % (e["id"], f))
            for ref in refs:
                path, _, name = ref.partition("::")
                p = root / path
                if not p.is_file():
                    out.append("%s: %s file not found: %s" % (e["id"], f, path))
                elif name and not _defines(p, name):
                    out.append("%s: %s has no func %s" % (e["id"], path, name))
        for s in affects(e):
            if s not in systems:
                out.append("%s: unknown system '%s'" % (e["id"], s))
    if index_block(entries, systems) not in text:
        out.append("the reverse dependency index is out of date (run with --write)")
    return out


def index_block(entries, systems):
    """The generated reverse index: for each system, the interactions that affect it."""
    lines = [INDEX_START, "", "| System | Interactions |", "|---|---|"]
    for s in systems:
        ids = [e["id"] for e in entries if s in affects(e)]
        lines.append("| %s | %s |" % (s, ", ".join(ids) if ids else "none"))
    lines += ["", INDEX_END]
    return "\n".join(lines)


def write_index(text):
    systems, entries = parse(text)
    start, end = text.index(INDEX_START), text.index(INDEX_END) + len(INDEX_END)
    return text[:start] + index_block(entries, systems) + text[end:]


def main(argv):
    text = DOC.read_text()
    if "--write" in argv:
        text = write_index(text)
        DOC.write_text(text)
    found = problems(text)
    for p in found:
        print("problem: " + p)
    _, entries = parse(text)
    print("%d interactions, %d problems" % (len(entries), len(found)))
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
