"""Generate the inventory and counts of a build's status audit from the requirements register.

The owner asked (2026-10-20, register B16-AUDIT) for a maintained report of where a build stands. The register is the
record (CLAUDE.md section 9a), so the report's tables are generated from it and never hand-edited: every entry with
`target_build` equal to the build, its status, what is implemented, what remains, evidence, blockers, whether the owner
is needed, and its completion class. Each entry may carry `b16_class` (blocker, required, verify, optional, deferral,
done) and `complexity` (S, M, L, XL); the scope growth is counted against the register at the previous build's release
commit. The hand-written parts of the document (summary, criteria, plan) sit outside the generated markers.

    python3 tools/build_status.py            # check the document is current (exit 1 if not)
    python3 tools/build_status.py --write    # regenerate docs/BUILD_16_STATUS.md between its markers
"""
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REG = ROOT / "docs/requirements/requirements.json"
DOC = ROOT / "docs/BUILD_16_STATUS.md"
BUILD = "16"
BASE = "a8760be"            # the Build 15 release commit: Build 16's scope as it began
START, END = "<!-- b16:start (generated by tools/build_status.py --write) -->", "<!-- b16:end -->"

GROUP = {
    "COMPLETE AND VERIFIED": "Complete",
    "ACTIVE DEVELOPMENT": "In progress",
    "PARTIALLY IMPLEMENTED": "In progress",
    "IMPLEMENTED — TESTING REQUIRED": "Pending testing",
    "AUTOMATED TESTS PASSED — PLAYTEST REQUIRED": "Pending testing",
    "APPROVED — NOT STARTED": "Not started",
    "BLOCKED": "Blocked",
    "DEFERRED": "Deferred",
    "SUPERSEDED": "Superseded",
    "CANCELED BY OWNER": "Canceled",
    "UNKNOWN — INVESTIGATION REQUIRED": "Not started",
}
CLASS = {"blocker": "Release blocker", "required": "Required feature", "verify": "Testing and verification",
         "optional": "Optional", "deferral": "Proposed deferral (owner)", "done": "Done", "owner": "Owner decision",
         "superseded": "Superseded"}
AREA = [("FSE-B", "Food-security defects"), ("FSE", "Food security, relief, family chest"), ("FARM", "Family farms and leases"),
        ("STALL", "Market stalls"), ("PAR", "Player-villager parity"), ("TIME", "Time model"), ("FAM", "Families and orphans"),
        ("REC", "Families and orphans"), ("EQ", "Equilibrium and acceptance"), ("WDR", "Equilibrium and acceptance"),
        ("WR", "Wildlife"), ("DVW", "Audits and measurements"), ("B7", "Economy defects"), ("OD", "Owner decisions"),
        ("SJD", "Judgment gate"), ("B16", "Status audit")]


def entries(text: str) -> list:
    r = json.loads(text)
    return r.get("entries", r.get("requirements"))


def area(i: str) -> str:
    for p, a in AREA:
        if i.startswith(p):
            return a
    return "Other"


def cell(s) -> str:
    s = " ".join(str(s).split())
    return s.replace("|", "/")


def render() -> str:
    reg = entries(REG.read_text())
    mine = [x for x in reg if str(x.get("target_build")) == BUILD]
    try:
        base = {x["id"] for x in entries(subprocess.check_output(["git", "show", f"{BASE}:docs/requirements/requirements.json"],
                cwd=ROOT, text=True)) if str(x.get("target_build")) == BUILD}
    except subprocess.CalledProcessError:
        base = set()
    groups = Counter(GROUP.get(x["status"], x["status"]) for x in mine)
    classes = Counter(x.get("b16_class", "unclassified") for x in mine)
    added = [x["id"] for x in mine if x["id"] not in base]
    out = [START, "", f"**{len(mine)} Build {BUILD} items in the register** ({len(base)} when Build {BUILD} began at the "
           f"Build 15 release `{BASE}`; **{len(added)} added since**).", "",
           "| Status | Items |", "|---|---|"]
    for g in ["Complete", "In progress", "Pending testing", "Not started", "Blocked", "Deferred", "Superseded"]:
        out.append(f"| {g} | {groups.get(g, 0)} |")
    out += ["", "| Completion class | Items |", "|---|---|"]
    for c in ["blocker", "required", "verify", "optional", "deferral", "owner", "done", "superseded"]:
        if classes.get(c):
            out.append(f"| {CLASS[c]} | {classes[c]} |")
    if classes.get("unclassified"):
        out.append(f"| Unclassified | {classes['unclassified']} |")
    out += ["", "Added since Build 16 began, by family: " + ", ".join(f"{k} {v}" for k, v in
            sorted(Counter(i.rsplit("-", 1)[0] for i in added).items())) + ".", ""]
    for a in dict.fromkeys(area(x["id"]) for x in mine):
        rows = [x for x in mine if area(x["id"]) == a]
        out += [f"### {a}", "", "| ID | Item | Status | Implemented | Remains | Evidence | Blockers / depends | Owner? | Class | Size |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for x in rows:
            hist = (x.get("history") or [{}])[-1].get("why", "")
            impl = x.get("implementation") or (hist if x["status"] != "APPROVED — NOT STARTED" else "")
            remain = "" if x["status"] in ("COMPLETE AND VERIFIED", "SUPERSEDED") else (x.get("next_action") or "; ".join(x.get("acceptance") or []))
            ev = ", ".join([f"`{c}`" for c in (x.get("commits") or [])] + ([str(x["tests"])] if x.get("tests") else []))
            blk = "; ".join(list(x.get("blockers") or []) + ["after " + d for d in (x.get("depends_on") or [])])
            if x.get("superseded_by"):
                blk = "superseded by " + str(x["superseded_by"])
            owner = "yes" if x.get("b16_class") in ("owner", "deferral") or "owner" in blk.lower() or x.get("kind") == "decision" and x["status"] != "COMPLETE AND VERIFIED" else ""
            out.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                x["id"], cell(x["title"])[:140], GROUP.get(x["status"], x["status"]), cell(impl)[:220], cell(remain)[:220],
                cell(ev)[:120], cell(blk)[:100], owner, CLASS.get(x.get("b16_class", ""), ""), x.get("complexity", "")))
        out.append("")
    out.append(END)
    return "\n".join(out)


def main() -> int:
    text = DOC.read_text() if DOC.exists() else ""
    if START not in text or END not in text:
        print(f"{DOC} has no generated section markers")
        return 1
    new = text[:text.index(START)] + render() + text[text.index(END) + len(END):]
    if "--write" in sys.argv:
        DOC.write_text(new)
        print(f"{DOC.relative_to(ROOT)} written")
        return 0
    if new != text:
        print(f"{DOC.relative_to(ROOT)} is stale: run tools/build_status.py --write")
        return 1
    print(f"{DOC.relative_to(ROOT)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
